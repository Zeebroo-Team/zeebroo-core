<?php

namespace Modules\CRM\Mail;

use Illuminate\Bus\Queueable;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Queue\SerializesModels;
use Modules\CRM\Models\InquiryReport;
use Modules\CRM\Services\InquiryStatusService;

/** A department's daily inquiry status report, emailed to management (InquiryReportService::send). */
class InquiryReportMail extends Mailable
{
    use Queueable, SerializesModels;

    public function __construct(
        public InquiryReport $report,
        public string $businessName,
    ) {}

    public function envelope(): Envelope
    {
        $data = $this->report->data ?? [];

        return new Envelope(subject: 'Daily inquiry status — ' . ($data['department']['name'] ?? 'Department')
            . ' — ' . $this->report->report_date?->format('j M Y')
            . ($this->businessName !== '' ? ' — ' . $this->businessName : ''));
    }

    public function content(): Content
    {
        return new Content(view: 'mail::emails.composed', with: ['bodyHtml' => $this->reportHtml()]);
    }

    public function reportHtml(): string
    {
        $data   = $this->report->data ?? [];
        $totals = $data['totals'] ?? [];
        $cats   = InquiryStatusService::CATEGORIES;
        $th     = 'style="text-align:left;padding:6px 8px;border-bottom:2px solid #e5e7eb;font-size:12px;color:#475569"';
        $td     = 'style="padding:6px 8px;border-bottom:1px solid #f1f5f9;font-size:13px"';
        $num    = 'style="padding:6px 8px;border-bottom:1px solid #f1f5f9;font-size:13px;text-align:right"';

        $html = '<h2 style="margin:0 0 4px">Daily inquiry status</h2>'
            . '<p style="margin:0 0 14px;color:#64748b">' . e($data['department']['name'] ?? '') . ' · ' . e($this->report->report_date?->format('l, j F Y') ?? '') . '</p>';

        // Department totals
        $html .= '<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;margin-bottom:16px"><tr>'
            . $this->tile('Assigned', $totals['total'] ?? 0, '#0f172a');
        foreach ($cats as $key => [$label, $color]) {
            $html .= $this->tile($label, $totals[$key] ?? 0, $color);
        }
        $html .= '</tr></table>';
        $html .= '<p style="margin:0 0 16px;color:#475569">Conversion to sale: <strong>' . e((string) ($totals['conversion_rate'] ?? 0)) . '%</strong></p>';

        // Per user
        $html .= '<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;width:100%"><thead><tr>'
            . '<th ' . $th . '>Staff member</th><th ' . $th . '>Assigned</th>';
        foreach ($cats as [$label]) {
            $html .= '<th ' . $th . '>' . e($label) . '</th>';
        }
        $html .= '<th ' . $th . '>Conversion</th></tr></thead><tbody>';
        foreach ($data['users'] ?? [] as $row) {
            $c = $row['counts'] ?? [];
            $html .= '<tr><td ' . $td . '>' . e($row['user']['name'] ?? '') . (($row['over_limit'] ?? 0) > 0 ? ' <span style="color:#b45309;font-size:11px">(' . (int) $row['over_limit'] . ' over limit)</span>' : '') . '</td>'
                . '<td ' . $num . '><strong>' . (int) ($c['total'] ?? 0) . '</strong></td>';
            foreach (array_keys($cats) as $key) {
                $html .= '<td ' . $num . '>' . (int) ($c[$key] ?? 0) . '</td>';
            }
            $html .= '<td ' . $num . '>' . e((string) ($c['conversion_rate'] ?? 0)) . '%</td></tr>';
        }
        if (empty($data['users'])) {
            $html .= '<tr><td ' . $td . ' colspan="' . (count($cats) + 3) . '">No staff in this department.</td></tr>';
        }
        $html .= '</tbody></table>';

        if (filled($this->report->review_note)) {
            $html .= '<p style="margin:16px 0 0;padding:10px 12px;background:#f8fafc;border-left:3px solid #7c3aed"><strong>Head of department\'s note:</strong><br>'
                . nl2br(e($this->report->review_note)) . '</p>';
        }

        return $html . '<p style="color:#64748b;font-size:12px;margin-top:16px">Each inquiry is counted once, at the furthest step it has reached. Generated by Zeebroo CRM.</p>';
    }

    private function tile(string $label, int $value, string $color): string
    {
        return '<td style="padding:8px 12px;border:1px solid #e5e7eb;text-align:center">'
            . '<div style="font-size:20px;font-weight:700;color:' . $color . '">' . $value . '</div>'
            . '<div style="font-size:11px;color:#64748b">' . e($label) . '</div></td>';
    }
}
